#!/usr/bin/env python3
"""Generates every paindu icon from one definition of the mark.

The mark is the Urdu letter pe (the first letter of paindu, and the P of PB: Punjab,
paindu browser) drawn as a furrow with its three dots as seeds beneath it. A small
"G" in the lower right, drawn as one of the rings from the GITAV logo, ties it to GITAV.

Writes:
  ../android/app/src/main/res/drawable/ic_launcher_foreground.xml   adaptive icon foreground
  ../android/app/src/main/res/drawable/ic_launcher_monochrome.xml   Android 13+ themed icon
  ../android/app/src/main/res/drawable/paindu_logo.xml              round logo used inside the app
  ../android/app/src/main/res/mipmap-anydpi-v26/ic_launcher.xml
  paindu-icon-1024.png, paindu-icon-preview.png

Run from this folder: python3 make_icons.py   (needs Pillow for the PNGs)
"""
import math
import os

# Palette
DEEP = "#0F4A2A"      # deep field green (icon ground)
GREEN = "#1F5A32"     # primary green
CREAM = "#F7F2E7"     # ground
MUSTARD = "#E0A82E"   # sarson, the mustard fields of Punjab
SOIL = "#2A2118"      # ink

# The Urdu letter pe: a bowl with three dots beneath, drawn as a furrow with three seeds.
BOWL = [((28,34),(25.5,49),(30,54.5),(42,54.5)), ((42,54.5),(42,54.5),(62,54.5),(62,54.5)), ((62,54.5),(72.5,54.5),(77.5,50.5),(76,41.5))]
BOWL_W = 6.4
SEEDS = [(42.5,66.5),(53.5,66.5),(48,75)]
SEED_R = 3.6
BADGE = (71.5,71.5); BADGE_R = 8.0; G_R = 4.1; G_W = 2.3; G_START_DEG = 42

def _sc(p, k=0.86, c=(53.0,55.0)):
    return (round(c[0]+(p[0]-c[0])*k,2), round(c[1]+(p[1]-c[1])*k,2))
BOWL = [tuple(_sc(p) for p in seg) for seg in BOWL]
SEEDS = [_sc(p) for p in SEEDS]
BOWL_W = round(BOWL_W*0.9,2); SEED_R = round(SEED_R*0.9,2)
BADGE = (70.5,70.5)

def bowl_path():
    (p0,_,_,_) = BOWL[0]
    s = f"M{p0[0]},{p0[1]}"
    for (_,c1,c2,p3) in BOWL:
        s += f" C{c1[0]},{c1[1]} {c2[0]},{c2[1]} {p3[0]},{p3[1]}"
    return s

def circle_path(cx,cy,r):
    return f"M{cx-r},{cy} a{r},{r} 0 1,0 {2*r},0 a{r},{r} 0 1,0 {-2*r},0 z"

def g_path():
    bx,by = BADGE; a = math.radians(G_START_DEG)
    sx,sy = bx+G_R*math.cos(a), by-G_R*math.sin(a)
    return f"M{sx:.2f},{sy:.2f} A{G_R},{G_R} 0 1,0 {bx+G_R:.2f},{by:.2f} L{bx+0.4:.2f},{by:.2f}"

def g_points(n=200):
    bx,by = BADGE; a0 = G_START_DEG; pts=[]
    for i in range(n+1):
        a = math.radians(a0 + (360-a0)*i/n)       # counter-clockwise on screen
        pts.append((bx+G_R*math.cos(a), by-G_R*math.sin(a)))
    for i in range(20): pts.append((bx+G_R-(G_R-0.4)*i/19, by))
    return pts

def bowl_points(n=120):
    pts=[]
    for (p0,c1,c2,p3) in BOWL:
        for i in range(n+1):
            t=i/n; u=1-t
            pts.append((u**3*p0[0]+3*u*u*t*c1[0]+3*u*t*t*c2[0]+t**3*p3[0], u**3*p0[1]+3*u*u*t*c1[1]+3*u*t*t*c2[1]+t**3*p3[1]))
    return pts


# ---------------------------------------------------------------- Android vector drawables

RES = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "android", "app", "src", "main", "res")
HEAD = '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by paindu/branding/make_icons.py. Edit that, not this. -->\n'


def stroke(path, color, width):
    return (f'    <path android:pathData="{path}" android:strokeColor="{color}" android:strokeWidth="{width}"\n'
            f'        android:strokeLineCap="round" android:strokeLineJoin="round" android:fillColor="#00000000" />\n')


def fill(path, color):
    return f'    <path android:pathData="{path}" android:fillColor="{color}" />\n'


def mark(letter, seed, badge_bg=None, badge_fg=None):
    out = stroke(bowl_path(), letter, BOWL_W)
    for (x, y) in SEEDS:
        out += fill(circle_path(x, y, SEED_R), seed)
    if badge_bg:
        out += fill(circle_path(BADGE[0], BADGE[1], BADGE_R), badge_bg)
        out += stroke(g_path(), badge_fg, G_W)
    return out


def vector(body, size=108, viewport=108):
    return (HEAD + f'<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            f'    android:width="{size}dp" android:height="{size}dp"\n'
            f'    android:viewportWidth="{viewport}" android:viewportHeight="{viewport}">\n{body}</vector>\n')


def write(rel, text):
    path = os.path.join(RES, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)


def write_android():
    write("drawable/ic_launcher_foreground.xml", vector(mark(CREAM, MUSTARD, CREAM, GREEN)))
    write("drawable/ic_launcher_monochrome.xml", vector(mark("#FF000000", "#FF000000")))
    # The in-app logo is the launcher icon as a circle: the middle 72 of the 108 canvas.
    body = ('    <group android:translateX="-18" android:translateY="-18">\n'
            + fill(circle_path(54, 54, 36), DEEP) + mark(CREAM, MUSTARD, CREAM, GREEN) + '    </group>\n')
    write("drawable/paindu_logo.xml", vector(body, size=72, viewport=72))
    write("mipmap-anydpi-v26/ic_launcher.xml", HEAD +
          '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
          '    <background android:drawable="@color/icon_ground" />\n'
          '    <foreground android:drawable="@drawable/ic_launcher_foreground" />\n'
          '    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />\n'
          '</adaptive-icon>\n')


# ---------------------------------------------------------------- PNG previews

def render(size, ground, letter, seed, badge_bg, badge_fg, mask="squircle"):
    from PIL import Image, ImageDraw
    S = size * 4
    k = S / 108
    im = Image.new("RGBA", (S, S), (0, 0, 0, 0))
    d = ImageDraw.Draw(im)
    d.rectangle([0, 0, S, S], fill=ground)

    def dot(x, y, r, c):
        d.ellipse([(x - r) * k, (y - r) * k, (x + r) * k, (y + r) * k], fill=c)

    for (x, y) in bowl_points():
        dot(x, y, BOWL_W / 2, letter)
    for (x, y) in SEEDS:
        dot(x, y, SEED_R, seed)
    dot(BADGE[0], BADGE[1], BADGE_R, badge_bg)
    for (x, y) in g_points():
        dot(x, y, G_W / 2, badge_fg)
    c = int(S * 18 / 108)  # launchers show the middle 72 of the 108 canvas
    im = im.crop((c, c, S - c, S - c))
    m = Image.new("L", im.size, 0)
    md = ImageDraw.Draw(m)
    if mask == "circle":
        md.ellipse([0, 0, im.size[0], im.size[1]], fill=255)
    elif mask == "squircle":
        md.rounded_rectangle([0, 0, im.size[0], im.size[1]], radius=int(im.size[0] * 0.28), fill=255)
    else:
        md.rectangle([0, 0, im.size[0], im.size[1]], fill=255)
    im.putalpha(m)
    return im.resize((size, size), Image.LANCZOS)


def write_pngs():
    from PIL import Image
    here = os.path.dirname(os.path.abspath(__file__))
    chosen = (DEEP, CREAM, MUSTARD, CREAM, GREEN)
    render(1024, *chosen, mask="square").save(os.path.join(here, "paindu-icon-1024.png"))
    sheet = Image.new("RGBA", (980, 380), "#EDE7D9")
    for i, m in enumerate(["squircle", "circle"]):
        sheet.alpha_composite(render(280, *chosen, mask=m), (40 + i * 320, 30))
        sheet.alpha_composite(render(72, *chosen, mask=m), (700, 40 + i * 110))
        sheet.alpha_composite(render(48, *chosen, mask=m), (800, 52 + i * 110))
        sheet.alpha_composite(render(32, *chosen, mask=m), (876, 60 + i * 110))
    sheet.alpha_composite(render(72, CREAM, GREEN, "#C98A1B", GREEN, CREAM), (700, 270))
    sheet.alpha_composite(render(72, "#C9892B", SOIL, CREAM, SOIL, MUSTARD), (800, 270))
    sheet.save(os.path.join(here, "paindu-icon-preview.png"))


if __name__ == "__main__":
    write_android()
    try:
        write_pngs()
    except ImportError:
        print("Pillow isn't installed: wrote the Android drawables, skipped the PNGs.")
